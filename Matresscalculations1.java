    private void jbtnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnProcessActionPerformed
    // PROCESS BUTTON LOGIC
                                            
        try {
            String name = txtName.getText();
            String product = jcmbProduct.getSelectedItem().toString();
            double price = Double.parseDouble(txtprice.getText());

            double vat = price * 0.15;
            double commission = price * 0.10; 
            double total = price + vat + commission;

            String message = "Customer: " + name + "\n"
                           + "Product: " + product + "\n"
                           + "Price: R" + price + "\n"
                           + "VAT (15%): R" + vat + "\n"
                           + "Commission: R" + commission + "\n"
                           + "Total: R" + total;

            javax.swing.JOptionPane.showMessageDialog(null, message);

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Please enter a valid price.");
        }
    


        
    }//GEN-LAST:event_jbtnProcessActionPerformed

